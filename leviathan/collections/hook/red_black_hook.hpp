struct red_black_hook : tree_node_interface
{
    // The header node of the red‑black tree is marked as a 
    // sentinel for distinction, and it is logically equivalent to a black node.
    enum class red_black_color { red, black, sentinel };

    red_black_hook* links[3];

    red_black_color color;

    constexpr void as_sentinel()
    {
        color = red_black_color::sentinel;
    }

    constexpr bool is_sentinel() const
    {
        return color == red_black_color::sentinel;
    }

    constexpr void link(bool insert_left, red_black_hook* p, red_black_hook& header)
    {
        this->insert_node_and_update_header(insert_left, p, header);

        auto& root = header.parent();
        auto x = this;

        // Rebalance
        while (x != root && x->parent()->color == red_black_color::red)
        {
            auto grand = x->parent()->parent();

            // The x's parent is left child
            if (x->parent() == grand->lchild())
            {
                auto uncle = grand->rchild();

                if (uncle && uncle->color == red_black_color::red)
                {
                    x->parent()->color = red_black_color::black;
                    uncle->color = red_black_color::black;
                    x->parent()->parent()->color = red_black_color::red;
                    x = x->parent()->parent();
                }
                else
                {
                    if (x == x->parent()->rchild())
                    {
                        x = x->parent();
                        x->rotate_left(root);
                    }

                    x->parent()->color = red_black_color::black;
                    x->parent()->parent()->color = red_black_color::red;
                    x->parent()->parent()->rotate_right(root);
                }
            }
            else
            {
                auto uncle = grand->lchild();

                if (uncle && uncle->color == red_black_color::red)
                {
                    x->parent()->color = red_black_color::black;
                    uncle->color = red_black_color::black;
                    x->parent()->parent()->color = red_black_color::red;
                    x = x->parent()->parent();
                }
                else
                {
                    if (x == x->parent()->lchild())
                    {
                        x = x->parent();
                        x->rotate_right(root);
                    }

                    x->parent()->color = red_black_color::black;
                    x->parent()->parent()->color = red_black_color::red;
                    x->parent()->parent()->rotate_left(root);
                }
            }
        }

        // maintain the root color
        root->color = red_black_color::black;
        header.color = red_black_color::sentinel;
    }

    constexpr void unlink(red_black_hook& header)
    {
        auto [successor, child, child_parent] = this->replace_node_with_successor(header);

        if (successor != this)
        {
            std::swap(color, successor->color);
        }

        // Rebalance, the code is generated by Copilot
        if (color == red_black_color::black)
        {
            while (child != header.parent() && (child == nullptr || child->color == red_black_color::black))
            {
                if (child == child_parent->lchild())
                {
                    auto sibling = child_parent->rchild();

                    if (sibling->color == red_black_color::red)
                    {
                        sibling->color = red_black_color::black;
                        child_parent->color = red_black_color::red;
                        child_parent->rotate_left(header.parent());
                        sibling = child_parent->rchild();
                    }

                    if ((sibling->lchild() == nullptr || sibling->lchild()->color == red_black_color::black) &&
                        (sibling->rchild() == nullptr || sibling->rchild()->color == red_black_color::black))
                    {
                        sibling->color = red_black_color::red;
                        child = child_parent;
                        child_parent = child_parent->parent();
                    }
                    else
                    {
                        if (sibling->rchild() == nullptr || sibling->rchild()->color == red_black_color::black)
                        {
                            sibling->lchild()->color = red_black_color::black;
                            sibling->color = red_black_color::red;
                            sibling->rotate_right(header.parent());
                            sibling = child_parent->rchild();
                        }

                        sibling->color = child_parent->color;
                        child_parent->color = red_black_color::black;
                        sibling->rchild()->color = red_black_color::black;
                        child_parent->rotate_left(header.parent());
                        break;
                    }
                }
                else
                {
                    auto sibling = child_parent->lchild();

                    if (sibling->color == red_black_color::red)
                    {
                        sibling->color = red_black_color::black;
                        child_parent->color = red_black_color::red;
                        child_parent->rotate_right(header.parent());
                        sibling = child_parent->lchild();
                    }

                    if ((sibling->rchild() == nullptr || sibling->rchild()->color == red_black_color::black) &&
                        (sibling->lchild() == nullptr || sibling->lchild()->color == red_black_color::black))
                    {
                        sibling->color = red_black_color::red;
                        child = child_parent;
                        child_parent = child_parent->parent();
                    }
                    else
                    {
                        if (sibling->lchild() == nullptr || sibling->lchild()->color == red_black_color::black)
                        {
                            sibling->rchild()->color = red_black_color::black;
                            sibling->color = red_black_color::red;
                            sibling->rotate_left(header.parent());
                            sibling = child_parent->lchild();
                        }

                        sibling->color = child_parent->color;
                        child_parent->color = red_black_color::black;
                        sibling->lchild()->color = red_black_color::black;
                        child_parent->rotate_right(header.parent());
                        break;
                    }
                }
            }

            if (child)
            {
                child->color = red_black_color::black;
            }
        }

        header.color = red_black_color::sentinel;
    }

};

